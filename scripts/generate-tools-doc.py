"""Generate docs/TOOLS.md from the tool manifest the binary actually serves.

The README claims 62 tools. That number is only worth anything if it is
generated from the same source the server answers `tools/list` with, so this
reads docs/tools.json rather than a hand-maintained list.

Run from the repository root:

    python scripts/generate-tools-doc.py

Pass --check to fail instead of writing, which is what CI should do so a
tool added without regenerating this page is a build failure.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "tools.json"
OUTPUT = ROOT / "docs" / "TOOLS.md"

HEADER = """# Tool reference

<!-- GENERATED BY scripts/generate-tools-doc.py - DO NOT EDIT BY HAND -->

Every tool the Delta Browser MCP server advertises, grouped by what it is for.
The same list is served live by `tools/list` and is asserted in the test suite,
so this page cannot drift from the binary without CI noticing.

Run `delta tools` for the machine-readable form, or `delta tools | jq` to pipe
it somewhere else.

**{count} tools in total.**

"""

GROUPS = [
    ("Navigation", ["navigate", "reload", "go_back", "go_forward", "wait_for"]),
    ("Reading the page", [
        "snapshot", "get_text", "get_attribute", "get_dom", "get_url",
        "get_title", "get_computed_style",
    ]),
    ("Interacting", [
        "click", "double_click", "right_click", "fill", "type", "check",
        "uncheck", "select_option", "hover", "drag", "press_key", "scroll",
        "evaluate", "upload_file",
    ]),
    ("Tabs", ["list_tabs", "new_tab", "switch_tab", "close_tab"]),
    ("Session state", ["save_state", "restore_state"]),
    ("Cookies", ["get_cookies", "set_cookie", "clear_cookies"]),
    ("Capture", [
        "screenshot", "annotate_screenshot", "save_pdf",
    ]),
    ("Observability", [
        "get_console_logs", "get_network_log", "save_har", "get_performance",
        "get_memory_usage", "intercept_request",
    ]),
    ("Testing", [
        "test_run", "test_assert_text", "test_assert_attr", "test_assert_url",
        "test_assert_visible", "test_report",
    ]),
    ("Efficiency", ["batch"]),
    ("Server control", [
        "server_status", "server_shutdown", "server_profile_list",
        "server_profile_set", "server_logs", "cdp_raw",
    ]),
]


def build():
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    tools = data["tools"] if isinstance(data, dict) else data
    by_name = {t["name"]: t for t in tools}

    grouped, seen = [], set()
    for title, names in GROUPS:
        entries = []
        for name in names:
            tool = by_name.get(name)
            if tool is None:
                continue
            seen.add(name)
            entries.append((name, tool.get("description", "").strip()))
        if entries:
            grouped.append((title, entries))

    leftovers = sorted(set(by_name) - seen)
    if leftovers:
        grouped.append(("Other", [(n, by_name[n].get("description", "")) for n in leftovers]))

    out = [HEADER.format(count=len(tools))]
    for title, entries in grouped:
        out.append(f"## {title}\n\n")
        out.append("| Tool | What it does |\n|---|---|\n")
        for name, desc in entries:
            clean = desc.replace("|", "\\|").replace("\n", " ")
            out.append(f"| `{name}` | {clean} |\n")
        out.append("\n")

    out.append(
        "## Why some tools exist\n\n"
        "`batch` and `snapshot { delta: true }` are not convenience wrappers.\n"
        "Each MCP message is a latency boundary, so batching several actions\n"
        "into one message and returning only the elements that changed are the\n"
        "two largest levers on agent runtime and context window. See\n"
        "[AGENTS.md](AGENTS.md).\n\n"
        "## Safety\n\n"
        "Page content is untrusted input. `evaluate` runs JavaScript in the\n"
        "page's origin and can reach anything the page can reach. Check\n"
        "`server_status` before assuming a sandbox boundary is in place.\n"
    )
    return "".join(out), tools


def main():
    text, tools = build()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("docs/TOOLS.md is stale; run scripts/generate-tools-doc.py")
            return 1
        print("docs/TOOLS.md is up to date (%d tools)" % len(tools))
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print("wrote %s (%d tools)" % (OUTPUT.relative_to(ROOT), len(tools)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
